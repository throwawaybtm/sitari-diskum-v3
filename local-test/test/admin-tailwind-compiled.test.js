'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8');

const indexHtml = read('Admin/Index.html');
const head = indexHtml.slice(indexHtml.indexOf('<head>'), indexHtml.indexOf('</head>'));
const compiled = read('Admin/TailwindCompiled.html');
const pkg = JSON.parse(read('maintenance/tailwind/package.json'));
const pinned = pkg.devDependencies.tailwindcss;

test('Admin/Index.html no longer loads the Tailwind Play CDN', () => {
  assert.doesNotMatch(indexHtml, /cdn\.tailwindcss\.com/);
  assert.doesNotMatch(head, /<script\b[^>]*\btailwind/i);
});

test('Admin/Index.html includes the compiled CSS in <head> after Stylesheet (same cascade order the Play CDN had)', () => {
  const stylesheetAt = head.indexOf("<?!= include('Stylesheet'); ?>");
  const compiledAt = head.indexOf("<?!= include('TailwindCompiled'); ?>");
  assert.ok(stylesheetAt >= 0, 'Stylesheet include must stay');
  assert.ok(compiledAt > stylesheetAt, 'TailwindCompiled must be included after Stylesheet');
  assert.equal(indexHtml.split("include('TailwindCompiled')").length - 1, 1, 'included exactly once');
});

test('TailwindCompiled is on the Admin include allowlist', () => {
  const match = read('Admin/Code.js').match(/const ADMIN_INCLUDE_FILES_\s*=\s*\[([^\]]*)\]/);
  assert.ok(match, 'ADMIN_INCLUDE_FILES_ must exist');
  const names = match[1].split(',').map(item => item.trim().replace(/^'|'$/g, ''));
  assert.ok(names.includes('TailwindCompiled'));
  assert.ok(fs.existsSync(path.join(ROOT, 'Admin', 'TailwindCompiled.html')), 'allowlisted file must exist');
});

test('every include in Admin/Index.html is allowlisted', () => {
  const match = read('Admin/Code.js').match(/const ADMIN_INCLUDE_FILES_\s*=\s*\[([^\]]*)\]/);
  const names = new Set(match[1].split(',').map(item => item.trim().replace(/^'|'$/g, '')));
  for (const [, name] of indexHtml.matchAll(/<\?!=\s*include\('([^']+)'\)\s*;?\s*\?>/g)) {
    assert.ok(names.has(name), `${name} is included by Index.html but missing from ADMIN_INCLUDE_FILES_`);
  }
});

test('local preview server inlines TailwindCompiled and leaves no template expression behind', () => {
  const { renderAdminHtml } = require('../server');
  const html = renderAdminHtml();
  assert.match(html, /<style id="tailwind-compiled">/);
  assert.doesNotMatch(html, /cdn\.tailwindcss\.com/);
  assert.doesNotMatch(html, /include\('TailwindCompiled'\)/);
  assert.ok(html.indexOf('id="tailwind-compiled"') > html.indexOf('</style>'), 'compiled CSS follows Stylesheet in the document');
});

test('compiled CSS is generated by the pinned Tailwind version', () => {
  assert.match(pinned, /^\d+\.\d+\.\d+$/, 'tailwindcss must be pinned to an exact version');
  assert.equal(pinned, '3.4.17', 'pin must match the version the Play CDN served when the revision was made');
  assert.ok(compiled.startsWith(`<!-- Generated by maintenance/build-tailwind.js (tailwindcss ${pinned}). `));
  assert.ok(compiled.includes(`tailwindcss v${pinned} `), 'banner must carry the pinned version');
  const lock = JSON.parse(read('maintenance/tailwind/package-lock.json'));
  assert.equal(lock.packages['node_modules/tailwindcss'].version, pinned, 'lockfile must match the pin');
});

test('compiled CSS is safe to serve through an Apps Script include', () => {
  assert.doesNotMatch(compiled, /<\?|\?>/, 'no scriptlet delimiters');
  assert.equal((compiled.match(/<\/style/gi) || []).length, 1, 'only the closing wrapper tag');
  assert.equal((compiled.match(/<style\b/gi) || []).length, 1);
  assert.doesNotMatch(compiled, /@import|url\(\s*['"]?(https?:)?\/\//i, 'no external fetches from the compiled CSS (URLs inside comments are fine)');
});

test('compiled CSS covers the Tailwind utilities used by the Admin shell', () => {
  for (const selector of ['.flex', '.hidden', '.grid', '.rounded-2xl', '.bg-slate-100\\/70', '.min-h-screen', '.antialiased', '.text-slate-800']) {
    assert.ok(compiled.includes(selector + ' {') || compiled.includes(selector + ','), `missing ${selector}`);
  }
  assert.match(compiled, /@media \(min-width: 768px\)/, 'responsive variants must be generated');
});
