#!/usr/bin/env node
'use strict';

// Dev-time generator for Admin/TailwindCompiled.html (precompiled Tailwind CSS).
// Run after any change to Tailwind classes in tracked Admin/*.html or Admin/*.js:
//   node maintenance/build-tailwind.js
// Output is committed. It is not part of any deploy step and never touches Public/.
// Requires `npm ci --prefix maintenance/tailwind` once (node_modules is gitignored).

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const TW_DIR = path.join(__dirname, 'tailwind');
const OUT_FILE = path.join(ROOT, 'Admin', 'TailwindCompiled.html');
const CLI = path.join(TW_DIR, 'node_modules', '.bin', process.platform === 'win32' ? 'tailwindcss.cmd' : 'tailwindcss');

function pinnedVersion() {
  const pkg = JSON.parse(fs.readFileSync(path.join(TW_DIR, 'package.json'), 'utf8'));
  const version = pkg.devDependencies && pkg.devDependencies.tailwindcss;
  if (!/^\d+\.\d+\.\d+$/.test(version || '')) throw new Error('tailwindcss must be pinned to an exact version in maintenance/tailwind/package.json');
  return version;
}

function compile() {
  if (!fs.existsSync(CLI)) throw new Error('Tailwind CLI not installed. Run: npm ci --prefix maintenance/tailwind');
  const css = execFileSync(CLI, [
    '-c', path.join(TW_DIR, 'tailwind.config.cjs'),
    '-i', path.join(TW_DIR, 'input.css')
  ], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
  return css.replace(/\r\n/g, '\n').trim();
}

function validate(css, version) {
  if (!css.includes('tailwindcss v' + version + ' ')) throw new Error('Unexpected Tailwind banner; installed version does not match the pin ' + version);
  if (/<\?|\?>/.test(css)) throw new Error('Compiled CSS contains an Apps Script scriptlet delimiter');
  if (/<\/style/i.test(css)) throw new Error('Compiled CSS contains </style');
}

function build() {
  const version = pinnedVersion();
  const css = compile();
  validate(css, version);
  const html = [
    '<!-- Generated by maintenance/build-tailwind.js (tailwindcss ' + version + '). Do not edit by hand. -->',
    '<style id="tailwind-compiled">',
    css,
    '</style>',
    ''
  ].join('\n');
  fs.writeFileSync(OUT_FILE, html);
  return { version, bytes: Buffer.byteLength(html) };
}

if (require.main === module) {
  const result = build();
  console.log('Wrote Admin/TailwindCompiled.html (' + result.bytes + ' bytes, tailwindcss ' + result.version + ')');
}

module.exports = { build, compile, validate, pinnedVersion };
